"""Build a compact, reproducible US configuration index from official EPA data."""
import csv
import hashlib
import io
import json
from pathlib import Path
from datetime import datetime, timezone
from urllib.request import urlopen
from zipfile import ZipFile

URL = 'https://www.fueleconomy.gov/feg/epadata/vehicles.csv.zip'
raw = urlopen(URL, timeout=90).read()
columns = ['id', 'year', 'make', 'model', 'displ', 'cylinders', 'trany', 'drive', 'fuelType1', 'fuelType2', 'atvType', 'VClass', 'comb08', 'city08', 'highway08', 'combE', 'eng_dscr']
years = {}
with ZipFile(io.BytesIO(raw)) as archive:
    for row in csv.DictReader(io.TextIOWrapper(archive.open('vehicles.csv'), encoding='utf-8-sig')):
        if int(row['year']) < 1995:
            continue
        years.setdefault(row['year'], []).append([row.get(key, '') for key in columns])
target = Path(__file__).resolve().parents[1] / 'public/data/catalog'
target.mkdir(parents=True, exist_ok=True)
version = hashlib.sha256(raw).hexdigest()
for year, rows in years.items():
    (target / f'{year}.json').write_text(json.dumps({'version': version, 'columns': columns, 'rows': rows}, separators=(',', ':')), encoding='utf-8')
(target / 'manifest.json').write_text(json.dumps({'publisher': 'US EPA / DOE FuelEconomy.gov', 'market': 'US', 'source': URL, 'documentation': 'https://www.fueleconomy.gov/feg/ws/index.shtml', 'retrievedAt': datetime.now(timezone.utc).isoformat(), 'version': version, 'years': sorted(map(int, years)), 'units': {'displ': 'L', 'comb08': 'US mpg', 'combE': 'kWh/100 mi'}, 'notice': 'Adapted US government reference data. Original EPA record IDs retained. No endorsement. EPA test results are not NRCan test results.'}, indent=2), encoding='utf-8')
print(f'Built {sum(map(len, years.values()))} configurations across {len(years)} years.')

(target.parents[2] / "shared/catalog-version.js").write_text("import nrcan from '../public/data/fuel/manifest.json' with { type: 'json' };\n// Regenerated by scripts/update-epa.py.\nexport const CATALOG_VERSION = 'core-config-v1:" + version + "' + ':' + nrcan.sources.map(source => source.sha256).join(':');\n", encoding="utf-8")
